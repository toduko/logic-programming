% нод_списък(+S, +N, X) - X е списък, който има най-много S на брой елемента, 
%                         всеки от които е четен, положителен и по-малък от 
%                         S, с НОД на елементите равен на N
нод_списък(S, N, X) :- между(0, S, K), генератор_списък(S, K, X), нод(X, N).

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%% ПОМОЩНИ ПРЕДИКАТИ %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% генератор_списък(+S, +K, L) - L е списък с K на брой положителни четни числа, 
%                               всяко от което е по-малко от S
генератор_списък(_, 0, []).
генератор_списък(S, K, [X|L]) :-
    K > 0,
    KMinus1 is K - 1,
    генератор_списък(S, KMinus1, L),
    между(1, S, X),
    X < S,
    0 is X mod 2.

% нод(+X, N) - N е най-големият общ делител на числата в N
нод([Z], Z).
нод([Z|X], N) :- нод(X, K), нод(Z, K, N).

% нод(+A, +B, C) - C е най-големият общ делител на числата A и B
нод(A, 0, A).
нод(A, B, C) :- B \= 0, R is A mod B, нод(B, R, C).

% между(+Lo, +Hi, X) - естественото число X е между естествените числа Lo и Hi
между(Lo, Hi, Lo) :- Lo =< Hi.
между(Lo, Hi, X) :- Lo < Hi, LoPlus1 is Lo + 1, между(LoPlus1, Hi, X).

