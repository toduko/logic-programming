% оцветяване(+G, +N) - съществува оцветяване на G с N на брой цвята, за което 
%                      никои два разноцветни върха не са свързани с ребро
оцветяване([V, E], N) :-
    разбиване(V, N, ColorSplit),
    not(( елемент(C1, ColorSplit),
          елемент(C2, ColorSplit),
          C1 \= C2,
          елемент(U1, C1),
          елемент(U2, C2),
          елемент([U1, U2], E) )).

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%% ПОМОЩНИ ПРЕДИКАТИ %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% разбиване(+L, +N, P) - P е разбиване на L на N непразни списъци
разбиване(L, N, P) :- пермутация(L, L1), разделяне(L1, N, P).

% пермутация(+L, P) - P се получава чрез разбъркване на елементите на списъка L
пермутация([], []).
пермутация([X|L], P) :-
    пермутация(L, PL),
    конкат(PL1, PL2, PL),
    конкат(PL1, [X|PL2], P).

% разделяне(+L, +N, P) - P е последователно разбиване на L на N непразни списъци
разделяне(L, 1, [L]) :- L = [_|_].
разделяне(L, N, [X|P]) :-
    N > 1,
    NMinus1 is N - 1,
    конкат(X, L1, L),
    X \= [],
    разделяне(L1, NMinus1, P).

% конкат(L, M, +K) - списъкът K се получава като конкатенираме списъците L и M
конкат([], M, M).
конкат([X|L], M, [X|K]) :- конкат(L, M, K).

% елемент(X, +L) - X е елемент на списъка L
елемент(X, [X|_]).
елемент(X, [_|L]) :- елемент(X, L).
